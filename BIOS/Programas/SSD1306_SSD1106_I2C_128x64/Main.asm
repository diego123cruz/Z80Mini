printStringHL:
	LD A, (HL)
	CP 0
	RET Z
	PUSH HL
	CALL printCharA
	POP HL
	INC HL
	JP printStringHL

	RET

printCharA:
	LD HL, FONT
	LD DE, $0000
	LD E, A
	ADD HL, DE
	ADD HL, DE
	ADD HL, DE
	ADD HL, DE
	ADD HL, DE
	ADD HL, DE
    LD   A, $40    ; control byte: fluxo de dados
    LD   B, 6      ; largura da fonte
    CALL send_i2c_block
    RET


; --------------------------------------------------------------------------
; SH1106_Init - inicializa o display
;   Entrada: nenhuma
;   Saida:   BC DE HL preservados
; --------------------------------------------------------------------------
SH1106_Init:
    LD   A, $AE         ; display off
    CALL send_cmd

    LD   A, $D5         ; clock divide ratio / oscillator freq
    CALL send_cmd
    LD   A, $80
    CALL send_cmd

    LD   A, $A8         ; multiplex ratio
    CALL send_cmd
    LD   A, $3F         ; 64 linhas (MUX = 63)
    CALL send_cmd

    LD   A, $D3         ; display offset
    CALL send_cmd
    LD   A, $00
    CALL send_cmd

    LD   A, $40         ; start line = 0
    CALL send_cmd

#if CHIP_SH1106
    LD   A, $AD         ; DC-DC control (charge pump do SH1106)
    CALL send_cmd
    LD   A, $8B         ; DC-DC on
    CALL send_cmd
#else
    LD   A, $8D         ; charge pump setting (SSD1306)
    CALL send_cmd
    LD   A, $14         ; charge pump on (usa VDD interno)
    CALL send_cmd
#endif

#if CHIP_FLIP
    LD   A, $A0         ; segment remap normal
    CALL send_cmd

    LD   A, $C0         ; COM scan normal 
    CALL send_cmd
#else
    LD   A, $A1         ; segment remap (espelha horizontal)
    CALL send_cmd

    LD   A, $C8         ; COM output scan direction (espelha vertical)
    CALL send_cmd
#endif

    LD   A, $DA         ; COM pins hardware config
    CALL send_cmd
    LD   A, $12
    CALL send_cmd

    LD   A, $81         ; contrast
    CALL send_cmd
    LD   A, $80
    CALL send_cmd

    LD   A, $D9         ; pre-charge period
    CALL send_cmd
    LD   A, $1F
    CALL send_cmd

    LD   A, $DB         ; VCOM deselect level
    CALL send_cmd
    LD   A, $40
    CALL send_cmd

    LD   A, $A4         ; entire display resume (mostra conteudo da RAM)
    CALL send_cmd

    LD   A, $A6         ; display normal (nao invertido)
    CALL send_cmd

    CALL delay_50ms

    LD   A, $AF         ; display on
    CALL send_cmd

    RET


; --------------------------------------------------------------------------
; SH1106_SetPage - seleciona pagina (0-7) e volta o cursor de coluna
; para o inicio (respeitando COL_OFFSET)
;   Entrada: A = numero da pagina (0-7)
;   Saida:   HL preservado
; Os 3 bytes de comando (pagina, coluna baixa, coluna alta) sao montados
; em PAGE_CMD e enviados numa unica transacao I2C.
; --------------------------------------------------------------------------
SH1106_SetPage:
    PUSH HL
    OR   $B0             ; comando "set page address" = $B0 | page
    LD   (PAGE_CMD), A

    LD   A, COL_OFFSET
    AND  $0F
    LD   (PAGE_CMD+1), A ; coluna baixa (nibble baixo, comando $00-$0F)

    LD   A, COL_OFFSET
    RRCA
    RRCA
    RRCA
    RRCA
    AND  $0F
    OR   $10
    LD   (PAGE_CMD+2), A ; coluna alta (nibble alto, comando $10-$1F)

    LD   HL, PAGE_CMD
    LD   A, $00           ; control byte: fluxo de comandos
    LD   B, 3
    CALL send_i2c_block

    POP  HL
    RET


; --------------------------------------------------------------------------
; SH1106_ClearAll - apaga a tela inteira (todas as 8 paginas, 128 colunas)
; Cada pagina e enviada como um unico bloco de 128 bytes zerados
; (1 Open/Close por pagina, em vez de 1 por byte).
; --------------------------------------------------------------------------
SH1106_ClearAll:
    LD   C, 0             ; contador de paginas
SH1106_ClearPage:
    LD   A, C
    CALL SH1106_SetPage

    LD   HL, ZERO_ROW
    LD   A, $40            ; control byte: fluxo de dados
    LD   B, SCR_WIDTH
    CALL send_i2c_block

    INC  C
    LD   A, C
    CP   SCR_PAGES
    JR   NZ, SH1106_ClearPage

    RET


; --------------------------------------------------------------------------
; send_i2c_block - envia um control byte seguido de varios bytes numa
; UNICA transacao I2C (1 Open/Close para o bloco inteiro).
;
;   Entrada: A  = control byte ($00 = comandos, $40 = dados)
;            HL = ponteiro para os bytes a enviar
;            B  = quantidade de bytes
;   Saida:   HL += B (avancado ate o fim do bloco enviado)
;            C preservado (B e reaproveitado como contador)
; --------------------------------------------------------------------------
send_i2c_block:
    PUSH BC              ; preserva B(quantidade) e C do chamador
    LD   C, A            ; C = control byte

    LD   A, oled
    CALL I2C_Open
    LD   A, C
    CALL I2C_Write        ; control byte enviado uma unica vez
send_i2c_block_loop:
    LD   A, (HL)
    CALL I2C_Write
    INC  HL
    DJNZ send_i2c_block_loop
    CALL I2C_Close

    POP  BC
    RET


; --------------------------------------------------------------------------
; SH1106_FlushBuffer - envia um buffer de RAM (128x64 = 1024 bytes,
; organizado como 8 paginas sequenciais de 128 bytes) para o display
;   Entrada: HL = endereco do buffer
;   Saida:   HL avancado ate o fim do buffer
; Cada pagina e enviada como um unico bloco de 128 bytes.
; --------------------------------------------------------------------------
SH1106_FlushBuffer:
    LD   C, 0             ; contador de paginas
SH1106_FlushPage:
    LD   A, C
    CALL SH1106_SetPage    ; HL preservado

    LD   A, $40            ; control byte: fluxo de dados
    LD   B, SCR_WIDTH
    CALL send_i2c_block    ; envia 128 bytes a partir de HL; HL += 128

    INC  C
    LD   A, C
    CP   SCR_PAGES
    JR   NZ, SH1106_FlushPage

    RET


; --------------------------------------------------------------------------
; Rotinas de baixo nivel I2C (byte unico - usadas so na inicializacao)
; --------------------------------------------------------------------------
send_cmd:
    PUSH AF
    LD   A, oled
    CALL I2C_Open
    LD   A, $00          ; control byte: fluxo de comandos
    CALL I2C_Write
    POP  AF
    CALL I2C_Write
    CALL I2C_Close
    RET

send_data:
    PUSH AF
    LD   A, oled
    CALL I2C_Open
    LD   A, $40          ; control byte: fluxo de dados
    CALL I2C_Write
    POP  AF
    CALL I2C_Write
    CALL I2C_Close
    RET

delay_50ms:
    LD   DE, $0032
    CALL delay
    RET


