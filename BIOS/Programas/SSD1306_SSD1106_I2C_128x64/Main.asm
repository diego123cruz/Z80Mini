    LD A,5
    CALL SH1106_SetPage
    LD HL, MSG6
    CALL printStringHL

    LD A,6
    CALL SH1106_SetPage
    LD HL, MSG7
    CALL printStringHL

    LD A,7
    CALL SH1106_SetPage
    LD HL, MSG8
    CALL printStringHL

    RET
