; ==========================================================================
; Driver SH1106 / SSD1306 (OLED 128x64) via I2C - Z80Mini
;
; Baseado no mesmo padrao I2C_Open/I2C_Write/I2C_Close usado no driver
; SSD1306 do repositorio (BIOS/Programas/Display oled ssd1306_128x32).
;
; Compativel com os dois chips atraves do switch CHIP_SH1106 abaixo.
; Os dois usam "page addressing mode" aqui (comum aos dois controladores),
; entao o unico codigo que realmente muda entre eles e:
;   - o comando de charge pump (SH1106: $AD,$8B / SSD1306: $8D,$14)
;   - o COL_OFFSET (SH1106 tem RAM de 132 colunas mas painel de 128 ->
;     desloca 2; SSD1306 e nativamente 128 colunas -> offset 0)
; Tudo o mais (comandos de pagina/coluna, remap, scan direction, etc.)
; e identico nos dois chips.
; ==========================================================================

CHIP_SH1106 .equ    0           ; 1 = compila para SH1106, 0 = compila para SSD1306
CHIP_FLIP	.equ	1			; 0 = Display normal, 1 = Display flip 

oled        .equ    $78         ; endereco I2C (0x3C << 1), ja com bit R/W
SCR_WIDTH   .equ    128
SCR_PAGES   .equ    8           ; 128x64 -> 8 paginas de 8 pixels

#if CHIP_SH1106
COL_OFFSET  .equ    2           ; SH1106: RAM de 132 col, painel usa so 128 (offset 2)
#else
COL_OFFSET  .equ    0           ; SSD1306: 128 colunas nativas, sem offset
#endif

    .org $8000


